package Basketball;

public class Players {
	//Create variables
	private String name;
	private int playerNumber;
	
	//Getting for name 
	public String getName() {
		return name;
	}
	
	//Setter for name
	public void setName(String name) {
		this.name = name;
	}
	
	//Getting for number 
	public int getPlayerNumber() {
		return playerNumber;
	}
	
	//Setter for number
	public void setPlayerNumber(int playerNumber) {
		this.playerNumber = playerNumber;
	}

}
